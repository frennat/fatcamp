// Copies the workout generator out of index.html into the `forge` edge function,
// so the watch (over cellular, phone out of range) gets the exact sessions the
// phone would make. index.html stays the single source of truth: everything
// between /* @forge:begin */ and /* @forge:end */ is copied verbatim.
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("../index.html", import.meta.url), "utf8");
const parts = [];
const re = /\/\* @forge:begin[^*]*\*\/\n([\s\S]*?)\/\* @forge:end \*\/\n/g;
let m;
while ((m = re.exec(html))) parts.push(m[1]);
if (parts.length < 6) throw new Error(`expected 6 @forge regions, found ${parts.length}`);

const out = `// GENERATED by scripts/build-forge.mjs from index.html. Do not edit by hand.
// deno-lint-ignore-file
/* The generator's browser-only neighbours, stubbed: nothing below touches the page. */
const document = { querySelector: () => null, querySelectorAll: () => [] };
const localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
const window = {};
function syncControls() {}
function save() {}
function track() {}
function toast() {}

${parts.join("\n")}

/** text + the person's saved kit and history in; a phone session and the watch's copy out. */
export function forge({ text, profile = {}, seed }) {
  state = blankProfile();
  if (Array.isArray(profile.equip) && profile.equip.length) state.equip = profile.equip.filter((e) => typeof e === "string");
  if (Array.isArray(profile.limits)) state.limits = profile.limits.filter((e) => typeof e === "string");
  if (Array.isArray(profile.history)) state.history = profile.history.slice(0, 14).map((h) => ({ mids: Array.isArray(h.mids) ? h.mids : [] }));
  if (typeof profile.unit === "string") state.unit = profile.unit;
  state.streak = profile.streak | 0;
  state.cfg = JSON.parse(JSON.stringify(DEFAULT_CFG));
  if (["home", "public", "body"].includes(profile.loc)) state.cfg.loc = profile.loc;
  const heard = askApply(String(text || ""));
  const cfg = JSON.parse(JSON.stringify(state.cfg));
  cfg.seed = Number.isFinite(seed) ? seed : (Math.random() * 1e9) | 0;
  const s = generate(cfg);
  return { heard, summary: askSummary(state.cfg), packed: packSession(s), watch: watchPayload(s) };
}
`;
writeFileSync(new URL("../supabase/functions/forge/gen.js", import.meta.url), out);
console.log(`  forge: ${parts.length} regions, ${out.length} bytes`);
